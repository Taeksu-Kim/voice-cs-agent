"""TTS 읽는 말 (csagent/voice/spoken.py)."""
import pytest

from csagent.voice.spoken import for_tts


@pytest.mark.parametrize("text, spoken", [
    ("토스유스카드 1234가 정상 상태예요.", "토스유스카드 일이삼사가 정상 상태예요."),
    ("고객센터 1644-2944로 문의해 주세요.", "고객센터 일육사사, 이구사사로 문의해 주세요."),
    ("주문번호 A3001 확인했어요.", "주문번호 에이 삼공공일 확인했어요."),
    ("끝 4자리 5678 카드", "끝 4자리 오육칠팔 카드"),
    ("30만 원을 보내셨어요.", "30만 원을 보내셨어요."),
    ("10월 12일에 발송됐어요.", "10월 12일에 발송됐어요."),
    ("평균 2영업일 안에 답해요.", "평균 2영업일 안에 답해요."),
    ("245mm로 교환", "245mm로 교환"),
    ("2026년 10월", "2026년 10월"),
    ("300,000원", "300,000원"),
    ("페널티 점수 7점", "페널티 점수 7점"),
])
def test_for_tts(text, spoken):
    assert for_tts(text) == spoken
